"""Deterministic, ownership-aware YAML manifests for source-file impact lookup.

Only MATMA-owned YAML is rewritten or removed. No user test or mock is touched.
Every destination is checked before the first write, and individual writes are
atomic. A multi-file rebuild cannot promise a transactional filesystem commit.
"""

from __future__ import annotations

import hashlib
import os
from pathlib import Path
import tempfile
from typing import Any

import yaml

HEADER = "# AUTO-GENERATED BY MATMA PYTHON INDEXER - DO NOT EDIT MANUALLY\n"
SCHEMA_VERSION = 1


class ManifestError(Exception):
    """An unsafe or unsuccessful index write, reported as a nonzero CLI error."""


def _has_ownership_header(first_line: bytes) -> bool:
    """Accept LF and CRLF headers, but never an unrelated user file."""
    return first_line.rstrip(b"\r\n") == HEADER.encode("utf-8").rstrip(b"\r\n")


def _sha(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def _path(root: Path, source_file: str) -> Path:
    """Translate a project-relative slash path without accepting traversal."""
    if not source_file or "\\" in source_file:
        raise ManifestError(f"Unsafe path spelling: {source_file!r}")
    path = Path(source_file)
    if path.is_absolute() or any(part in ("..", "") for part in path.parts):
        raise ManifestError(f"Unsafe path outside project: {source_file!r}")
    candidate = Path(os.path.normpath(str(root / path)))
    if not candidate.is_relative_to(root):
        raise ManifestError(f"Unsafe path outside project: {source_file!r}")
    return candidate


def _symlink_ancestor(root: Path, path: Path) -> Path | None:
    cursor = path
    while cursor != root:
        if cursor.is_symlink():
            return cursor
        if root not in cursor.parents:
            return cursor
        cursor = cursor.parent
    return root if root.is_symlink() else None


def _preflight_path(root: Path, tests_mirror: Path, path: Path) -> None:
    if not path.is_relative_to(tests_mirror):
        raise ManifestError(f"Manifest path must be inside {tests_mirror}: {path}")
    link = _symlink_ancestor(root, path)
    if link is not None:
        raise ManifestError(f"Refusing symlinked manifest destination: {link}")
    if path.exists():
        if not path.is_file():
            raise ManifestError(f"Manifest destination is not a file: {path}")
        try:
            with path.open("rb") as stream:
                first = stream.readline()
        except OSError as exc:
            raise ManifestError(f"Cannot read existing manifest {path}: {exc}") from exc
        if not _has_ownership_header(first):
            raise ManifestError(f"Refusing to overwrite user-owned YAML: {path}")


def _yaml(payload: dict[str, Any]) -> bytes:
    return (HEADER + yaml.safe_dump(payload, sort_keys=False, allow_unicode=True, width=100)).encode("utf-8")


def _atomic_write(path: Path, contents: bytes) -> bool:
    """Write only if the byte representation changed; preserve timestamps otherwise."""
    if path.is_file() and path.read_bytes() == contents:
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, temp = tempfile.mkstemp(prefix=".matma-", suffix=".tmp", dir=path.parent)
    try:
        with os.fdopen(fd, "wb") as output:
            output.write(contents)
            output.flush()
            os.fsync(output.fileno())
        os.replace(temp, path)
    finally:
        if os.path.exists(temp):
            os.unlink(temp)
    return True


def fingerprint_inputs(project_root: Path, files: list[dict[str, Any]],
                       source_roots: list[str]) -> tuple[str, list[dict[str, str]]]:
    """A content fingerprint independent of machine-local absolute paths."""
    entries = []
    for item in sorted(files, key=lambda f: f["source_file"]):
        file = item["source_file"]
        path = _path(project_root, file)
        if _symlink_ancestor(project_root, path) is not None:
            raise ManifestError(f"Source turned into symlink during indexing: {file}")
        try:
            content_hash = _sha(path.read_bytes())
        except OSError as exc:
            raise ManifestError(f"Could not hash source {file}: {exc}") from exc
        entries.append({"source_file": file, "sha256": content_hash})
    serialized = "".join(f"{s}\0{h}\n" for s, h in (
        (entry["source_file"], entry["sha256"]) for entry in entries
    ))
    serialized += "ROOTS\n" + "\n".join(sorted(source_roots)) + "\n"
    return _sha(serialized.encode("utf-8")), entries


def _directory_inventory(root: Path, sources: list[dict[str, str]], source_roots: list[str]) -> list[dict[str, Any]]:
    """Watch only configured source trees, not unrelated project ancestors.

    Watching the repository root for a `src/` project causes false stale
    indexes whenever pytest, an IDE or another tool creates `.pytest_cache/`
    beside the source root. A flat source-root `.` legitimately tracks `.`.
    """
    roots = {Path(name) for name in source_roots}
    directories = set(source_roots)
    for item in sources:
        cursor = Path(item["source_file"]).parent
        while True:
            if not any(cursor == selected or selected in cursor.parents for selected in roots):
                break
            directories.add(cursor.as_posix())
            if cursor in roots or cursor.parent == cursor:
                break
            cursor = cursor.parent
    found = []
    for name in sorted(directories):
        path = _path(root, name)
        try:
            found.append({"path": name, "mtime_ns": path.stat().st_mtime_ns})
        except OSError as exc:
            raise ManifestError(f"Could not stat source directory {name}: {exc}") from exc
    return found


def _manifest_for(item: dict[str, Any], graph: dict[str, Any], by_source: dict[str, dict[str, Any]],
                  fingerprint: str, diagnostics: list[dict[str, Any]]) -> dict[str, Any]:
    source_file = item["source_file"]
    levels = {}
    for level, paths in graph["dependents"][source_file].items():
        levels[level] = [
            {
                "module_name": by_source[path]["module_name"],
                "source_file": path,
                "unit_test": by_source[path]["mirrors"]["unit_test"],
                "interaction_test": by_source[path]["mirrors"]["interaction_test"],
            }
            for path in paths
        ]
    warnings = [{"code": d["code"], "line": d.get("line"), "message": d["message"]}
                for d in diagnostics if d.get("file") == source_file and d["severity"] == "warning"]
    return {
        "schema_version": SCHEMA_VERSION,
        "index_fingerprint": fingerprint,
        "module_name": item["module_name"],
        "source_file": source_file,
        "is_package": item["is_package"],
        "testable": item["testable"],
        "symbols": item["symbols"],
        "mirrors": item["mirrors"],
        "dependencies": graph["dependencies"][source_file],
        "external_dependencies": graph["external_dependencies"][source_file],
        "dynamic_references": item["dynamic_imports"],
        "warnings": warnings,
        "dependents": levels,
    }


def write_manifests(root: Path, tests_root: str, examined: dict[str, Any], graph: dict[str, Any]) -> dict[str, Any]:
    """Preflight all output, then safely replace owned YAML and prune stale YAML.

    All source files are indexed even when an index command specifies --target.
    The target only affects the index command's output; graph is always global.
    """
    project_root = root.resolve()
    by_source = {mod["source_file"]: mod for mod in examined["files"]}
    source_roots = examined["summary"]["source_roots"]
    fingerprint, source_hashes = fingerprint_inputs(project_root, examined["files"], source_roots)
    test_root = _path(project_root, tests_root)
    mirror = test_root / "mirror"
    proposed: dict[Path, bytes] = {}
    for source, item in sorted(by_source.items()):
        output = _path(project_root, item["mirrors"]["manifest"])
        proposed[output] = _yaml(_manifest_for(item, graph, by_source, fingerprint, examined["diagnostics"]))
    metadata_path = mirror / ".index.auto.yaml"
    # The eventual metadata is populated once the other files have been written
    # so directory mtimes reflect any newly created manifest tier.
    planned = [*proposed, metadata_path]
    for output in planned:
        _preflight_path(project_root, mirror, output)

    stale = []
    if mirror.exists():
        for dirname, dirs, filenames in os.walk(mirror, topdown=True, followlinks=False):
            directory = Path(dirname)
            for name in dirs:
                if (directory / name).is_symlink():
                    raise ManifestError(f"Symlink in generated manifest tree: {directory / name}")
            for name in filenames:
                path = directory / name
                if path.is_symlink():
                    raise ManifestError(f"Symlink in generated manifest tree: {path}")
                if path in proposed or path == metadata_path or not name.endswith(".auto.yaml"):
                    continue
                if path.is_file():
                    with path.open("rb") as handle:
                        owned = _has_ownership_header(handle.readline())
                    if owned:
                        stale.append(path)
    written: list[str] = []
    unchanged: list[str] = []
    removed: list[str] = []
    try:
        for path, contents in sorted(proposed.items(), key=lambda pair: pair[0].as_posix()):
            bucket = written if _atomic_write(path, contents) else unchanged
            bucket.append(path.relative_to(project_root).as_posix())
        # Source directories are recorded after the mirror may have been created.
        metadata = {
            "schema_version": SCHEMA_VERSION,
            "index_fingerprint": fingerprint,
            "source_roots": sorted(source_roots),
            "tests_root": tests_root,
            "sources": source_hashes,
            "directories": _directory_inventory(project_root, source_hashes, source_roots),
            # Phase 5 resolves source paths, import names and qualified symbols
            # without opening every YAML manifest or reparsing Python modules.
            "module_to_source": dict(sorted(examined.get("module_to_source", {
                item["module_name"]: item["source_file"] for item in examined["files"]
            }).items())),
            "symbol_to_source": dict(sorted(examined.get("symbol_to_source", {
                f"{item['module_name']}.{symbol['qualname']}": item["source_file"]
                for item in examined["files"] for symbol in item["symbols"]
            }).items())),
            "source_to_manifest": {key: by_source[key]["mirrors"]["manifest"]
                                   for key in sorted(by_source)},
            "warnings_by_source": {
                key: sorted((d for d in examined["diagnostics"]
                             if d.get("file") == key and d.get("severity") == "warning"),
                            key=lambda d: (d.get("line") or 0, d.get("column") or 0, d["code"]))
                for key in sorted(by_source)
            },
        }
        bucket = written if _atomic_write(metadata_path, _yaml(metadata)) else unchanged
        bucket.append(metadata_path.relative_to(project_root).as_posix())
        # Stale removals happen only once all desired files were successfully written.
        for path in sorted(stale):
            path.unlink()
            removed.append(path.relative_to(project_root).as_posix())
    except OSError as exc:
        raise ManifestError(f"Index regeneration failed: {exc}") from exc
    return {
        "index_fingerprint": fingerprint,
        "manifests": {"written": sorted(written), "unchanged": sorted(unchanged), "removed": sorted(removed)},
    }
